#!/usr/bin/env python3
"""Generate the paper's result table and headline numbers from the raw CSVs.

Reads the summary CSV produced by summarize-batch.py (one row per run) and
writes paper/data/results.tex, which main.tex \\input's. Nothing is typed by
hand, so the paper cannot drift from the measurements.

Usage:
  update-results.py <summary.csv> [--out paper/data/results.tex]
"""
from __future__ import annotations

import argparse
import csv
import math
import os
import statistics
import sys


def clopper_pearson(k: int, n: int) -> tuple[float, float]:
    """Exact 95% interval via bisection on the regularised incomplete beta."""

    def betacf(a: float, b: float, x: float) -> float:
        qab, qap, qam = a + b, a + 1.0, a - 1.0
        c, d = 1.0, 1.0 - qab * x / qap
        d = 1e-30 if abs(d) < 1e-30 else 1.0 / d
        h = d
        for m in range(1, 300):
            m2 = 2 * m
            aa = m * (b - m) * x / ((qam + m2) * (a + m2))
            d = 1.0 + aa * d
            d = 1e-30 if abs(d) < 1e-30 else 1.0 / d
            c = 1.0 + aa / c
            c = 1e-30 if abs(c) < 1e-30 else c
            h *= d * c
            aa = -(a + m) * (qab + m) * x / ((a + m2) * (qap + m2))
            d = 1.0 + aa * d
            d = 1e-30 if abs(d) < 1e-30 else 1.0 / d
            c = 1.0 + aa / c
            c = 1e-30 if abs(c) < 1e-30 else c
            de = d * c
            h *= de
            if abs(de - 1.0) < 1e-12:
                break
        return h

    def betai(a: float, b: float, x: float) -> float:
        if x <= 0.0:
            return 0.0
        if x >= 1.0:
            return 1.0
        lbeta = math.lgamma(a) + math.lgamma(b) - math.lgamma(a + b)
        front = math.exp(-lbeta + a * math.log(x) + b * math.log(1.0 - x))
        if x < (a + 1.0) / (a + b + 2.0):
            return front * betacf(a, b, x) / a
        return 1.0 - front * betacf(b, a, 1.0 - x) / b

    def invert(p: float, a: float, b: float) -> float:
        lo, hi = 0.0, 1.0
        for _ in range(200):
            mid = (lo + hi) / 2
            if betai(a, b, mid) < p:
                lo = mid
            else:
                hi = mid
        return (lo + hi) / 2

    low = 0.0 if k == 0 else invert(0.025, k, n - k + 1)
    high = 1.0 if k == n else invert(0.975, k + 1, n - k)
    return low, high


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("csv")
    ap.add_argument("--out", default="paper/data/results.tex")
    ap.add_argument("--ab", help="optional CSV from the kick on/off A/B")
    ap.add_argument("--control", help="optional CSV from the control batch")
    ap.add_argument("--exposure", help="optional handover-exposure.txt")
    args = ap.parse_args()

    rows = list(csv.DictReader(open(args.csv)))
    runs = [r for r in rows if r.get("control") in ("False", "false", "")]
    ok = [r for r in runs if r.get("ok") in ("True", "true")]
    n, k = len(runs), len(ok)
    if n == 0:
        print("no runs in csv")
        return 1
    lo, hi = clopper_pearson(k, n)
    dt = [float(r["downtime_ms"]) for r in runs if r.get("downtime_ms")]
    cp = [float(r["copy_s"]) for r in runs if r.get("copy_s")]
    ks = [int(r["kicks"]) for r in runs if r.get("kicks")]
    st = [int(r["stale"]) for r in runs if r.get("stale")]

    def f1(x: float) -> str:
        return f"{x:.1f}"

    lines = ["% GENERATED by guest/../paper/update-results.py -- do not edit by hand.",
             f"% source: {os.path.basename(args.csv)}",
             ""]
    lines += [
        f"\\newcommand{{\\TotalRuns}}{{{n}}}",
        f"\\newcommand{{\\PassCount}}{{{k}}}",
        f"\\newcommand{{\\DowntimeMin}}{{{dt and f'{min(dt):.0f}' or '?'}}}",
        f"\\newcommand{{\\DowntimeMedian}}{{{dt and f1(statistics.median(dt)) or '?'}}}",
        f"\\newcommand{{\\DowntimeMax}}{{{dt and f'{max(dt):.0f}' or '?'}}}",
        f"\\newcommand{{\\CopyMin}}{{{cp and f1(min(cp)) or '?'}}}",
        f"\\newcommand{{\\CopyMedian}}{{{cp and f1(statistics.median(cp)) or '?'}}}",
        f"\\newcommand{{\\CopyMax}}{{{cp and f1(max(cp)) or '?'}}}",
        f"\\newcommand{{\\CILow}}{{{lo:.2f}}}",
        f"\\newcommand{{\\CIHigh}}{{{hi:.2f}}}",
        f"\\newcommand{{\\FailUpper}}{{{k == n and f'{1 - 0.05 ** (1 / n):.2f}' or 'n/a'}}}",
        f"\\newcommand{{\\PassLowerOneSided}}{{{k == n and f'{0.05 ** (1 / n):.2f}' or 'n/a'}}}",
        f"\\newcommand{{\\KickMin}}{{{ks and min(ks) or '?'}}}",
        f"\\newcommand{{\\KickMax}}{{{ks and max(ks) or '?'}}}",
        f"\\newcommand{{\\StaleMin}}{{{st and min(st) or '?'}}}",
        f"\\newcommand{{\\StaleMax}}{{{st and max(st) or '?'}}}",
        "",
    ]

    # hand-over exposure, if the analysis file is available
    if args.exposure and os.path.exists(args.exposure):
        txt = open(args.exposure).read()
        rows_exp = [l.split() for l in txt.splitlines()
                    if l.strip() and not l.startswith(("run", "runs ", "total", "worst"))]
        expos = [(int(r[1]), float(r[3])) for r in rows_exp if len(r) >= 4 and r[1].isdigit()]
        if expos:
            windows = [w for _, w in expos]
            n_exp = sum(1 for e, _ in expos if e > 0)
            tot = sum(e for e, _ in expos)
            lines += [
                f"\\newcommand{{\\ExposureWindowMin}}{{{min(windows):.1f}}}",
                f"\\newcommand{{\\ExposureWindowMax}}{{{max(windows):.1f}}}",
                f"\\newcommand{{\\ExposureRuns}}{{{n_exp}}}",
                f"\\newcommand{{\\ExposureMeasured}}{{{len(expos)}}}",
                f"\\newcommand{{\\ExposureCompletions}}{{{tot}}}",
                f"\\newcommand{{\\ExposureWorst}}{{{max(e for e, _ in expos)}}}",
                f"\\newcommand{{\\ExposureRate}}{{{100.0 * n_exp / len(expos):.0f}}}",
                "",
            ]

    # table body: run index, downtime, copy duration, spans, integrity
    body = ["% table body: one row per run", "\\midrule"]
    for i, r in enumerate(runs, 1):
        spans = "yes" if r.get("spans") == "YES" else "no"
        md5 = "match" if r.get("md5") == "MATCH" else "mismatch"
        le = r.get("late_enum") or "?"
        body.append(f"{i} & {r.get('downtime_ms') or '?'} & {r.get('copy_s') or '?'} & "
                    f"{spans} & {md5} / {le} \\\\")
    body.append("\\bottomrule")
    lines += ["\\newcommand{\\ResultsTableBody}{%", *body, "}", ""]

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    print(f"wrote {args.out}")
    print(f"  runs={n} pass={k} CI=[{lo:.2f},{hi:.2f}] "
          f"downtime={min(dt):.0f}/{statistics.median(dt):.1f}/{max(dt):.0f}ms "
          f"copy={min(cp):.1f}/{statistics.median(cp):.1f}/{max(cp):.1f}s")

    # regenerate the figure data as well
    with open("paper/data/runs.dat", "w") as fh:
        for i, r in enumerate(runs, 1):
            fh.write(f"{i} {r.get('downtime_ms') or 0} {r.get('copy_s') or 0}\n")
    print("  rewrote paper/data/runs.dat")

    if args.ab and os.path.exists(args.ab):
        ab = list(csv.DictReader(open(args.ab)))
        for arm in ("on", "off"):
            sub = [r for r in ab if arm in r.get("run", "")]
            kk, nn = sum(r.get("ok") in ("True", "true") for r in sub), len(sub)
            print(f"  A/B kick={arm}: {kk}/{nn} passed")
    return 0


if __name__ == "__main__":
    sys.exit(main())
